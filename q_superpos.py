# ============================================
# ファイル名  : q_single_superposition.py
# 目的       : 1量子ビットにHadamardゲートを適用して重ね合わせ状態を生成し、
#              測定により得られる確率分布（0または1）を統計的に確認する。
#
# 処理内容   :
#   - 初期状態 |0> の量子ビットに H（Hadamard）ゲートを適用し、
#     |0> + |1> の重ね合わせ状態を作る（理論上は0と1が50%ずつ出る）。
#   - 測定ゲートにより状態を観測（|0⟩ または |1⟩ に収束）。
#   - 1024回測定を繰り返し、出現回数（0 or 1）をカウント。
#
# 測定結果   : '0'または'1' のビット列（1ビット）の出現回数を辞書形式で出力。
#              理想的には {'0': 約512, '1': 約512} に近づく。
#
# 出力       : 測定結果（コンソール） ※ グラフ表示や保存なし
# ============================================

# Qiskitの基本モジュール：量子回路生成と変換
from qiskit import QuantumCircuit, transpile

# Aerシミュレータ：Qiskit標準のローカル量子回路実行エンジン
from qiskit_aer import AerSimulator

# --- Step 1: 回路の作成（1量子ビット + 1古典ビット） ---
qc = QuantumCircuit(1, 1)

# --- Step 2: Hadamardゲートで重ね合わせ状態を生成 ---
qc.h(0)  # 入力状態 |0⟩ → (|0⟩ + |1⟩)/√2 に変換

# --- Step 3: 測定（量子ビット0を古典ビット0に写す） ---
qc.measure(0, 0)

# --- Step 4: シミュレータを取得し回路を最適化 ---
sim = AerSimulator()
qc2 = transpile(qc, sim)

# --- Step 5: 実行（1024ショット） ---
job = sim.run(qc2, shots=1024)
res = job.result()
counts = res.get_counts(qc2)

# --- Step 6: 結果表示（0と1の出現回数） ---
print("測定結果（重ね合わせ状態 |0> + |1> の統計）:", counts)

